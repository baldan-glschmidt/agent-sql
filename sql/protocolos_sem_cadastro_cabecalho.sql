-- VALIDAR E INSERIR OS PROTOCOLOS SEM CADASTRO NO CABEÇALHO
INSERT INTO USU_TNUMPTC (
    USU_NUMPTC,
    USU_CODCCU
)
SELECT DISTINCT
    D.USU_NUMPTC,
    D.USU_CODCCU
FROM USU_TDESINT D
WHERE D.USU_DATENV > TO_DATE('01/01/2026', 'DD/MM/YYYY')
 AND NOT EXISTS (
    SELECT 1
    FROM USU_TNUMPTC C
    WHERE C.USU_NUMPTC = D.USU_NUMPTC
      AND C.USU_CODCCU = D.USU_CODCCU
);